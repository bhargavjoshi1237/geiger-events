import { WorkspaceError } from "../errors.js";
import { BUCKET } from "../server/store.js";
import { adminClient } from "../../supabase/admin.js";

function db() {
  const client = adminClient();
  if (!client) throw new WorkspaceError("service_unavailable", 503, "Workspace is unavailable.");
  return client;
}

function checked(result) {
  if (result.error) throw result.error;
  return result.data;
}

const scope = (query, context) => query.eq("project_id", context.projectId).eq("event_id", context.eventId);

export const documentRow = (row) => row && ({
  id: row.id, kind: row.kind, name: row.name, objectId: row.object_id, config: row.config, revision: Number(row.revision),
  createdBy: row.created_by, updatedBy: row.updated_by, createdAt: row.created_at, updatedAt: row.updated_at, deletedAt: row.deleted_at,
});

export const certificateRow = (row) => row && ({
  id: row.id, documentId: row.document_id, recordId: row.record_id, code: row.code, title: row.title, holder: row.holder, data: row.data,
  fileId: row.file_id, issuedByKind: row.issued_by_kind, issuedBy: row.issued_by, issuedAt: row.issued_at,
  revokedAt: row.revoked_at, revokedReason: row.revoked_reason,
});

export const documentStore = {
  async documents(context) {
    return checked(await scope(db().from("workspace_documents").select("*"), context).is("deleted_at", null).order("name")).map(documentRow);
  },
  async document(context, id) {
    return documentRow(checked(await scope(db().from("workspace_documents").select("*"), context).eq("id", id).is("deleted_at", null).maybeSingle()));
  },
  async insertDocument(row) {
    return documentRow(checked(await db().from("workspace_documents").insert(row).select("*").single()));
  },
  // Optimistic update: refuses when someone saved in between.
  async updateDocument(context, id, patch, expectedRevision = null) {
    let query = scope(db().from("workspace_documents").update({ ...patch, updated_at: new Date().toISOString() }), context).eq("id", id);
    if (expectedRevision !== null) query = query.eq("revision", expectedRevision);
    const rows = checked(await query.select("*"));
    if (!rows.length) throw new WorkspaceError("revision_conflict", 409, "Someone else changed this document. Reload and try again.");
    return documentRow(rows[0]);
  },

  async certificates(context, { recordId = null, documentId = null, status = null, limit = 200 } = {}) {
    let query = scope(db().from("workspace_certificates").select("*"), context);
    if (recordId) query = query.eq("record_id", recordId);
    if (documentId) query = query.eq("document_id", documentId);
    if (status === "valid") query = query.is("revoked_at", null);
    if (status === "revoked") query = query.not("revoked_at", "is", null);
    return checked(await query.order("issued_at", { ascending: false }).limit(limit)).map(certificateRow);
  },
  async certificate(context, id) {
    return certificateRow(checked(await scope(db().from("workspace_certificates").select("*"), context).eq("id", id).maybeSingle()));
  },
  async certificateById(id) {
    return certificateRow(checked(await db().from("workspace_certificates").select("*").eq("id", id).maybeSingle()));
  },
  // Inserts a certificate; a repeated id (an automation retrying) returns the one already issued.
  async issue(row) {
    const inserted = await db().from("workspace_certificates").insert(row).select("*").maybeSingle();
    if (!inserted.error) return { certificate: certificateRow(inserted.data), created: true };
    if (inserted.error.code !== "23505") throw inserted.error;
    const existing = await this.certificateById(row.id);
    if (!existing) throw inserted.error;
    return { certificate: existing, created: false };
  },
  async revoke(context, ids, reason) {
    if (!ids.length) return;
    checked(await scope(db().from("workspace_certificates").update({ revoked_at: new Date().toISOString(), revoked_reason: reason }), context)
      .in("id", ids).is("revoked_at", null));
  },
  async publicCertificate(eventId, code) {
    return checked(await db().rpc("workspace_certificate_public", { p_event: eventId, p_code: code }));
  },

  // Uploads generated bytes; an object that's already there (a retried run) counts as uploaded.
  async upload(path, bytes, contentType = "application/pdf") {
    const { error } = await db().storage.from(BUCKET).upload(path, bytes, { contentType, upsert: false });
    if (error && !/exists|duplicate/i.test(`${error.message ?? ""} ${error.error ?? ""} ${error.statusCode ?? ""}`)) throw error;
  },
  async signedUrl(path, seconds, name) {
    return checked(await db().storage.from(BUCKET).createSignedUrl(path, seconds, name ? { download: name } : undefined)).signedUrl;
  },
  async addFile(row) {
    const inserted = await db().from("workspace_files").insert(row).select("*").maybeSingle();
    if (!inserted.error) return inserted.data;
    if (inserted.error.code !== "23505") throw inserted.error;
    return checked(await db().from("workspace_files").select("*").eq("id", row.id).single());
  },
  async file(context, id) {
    return checked(await scope(db().from("workspace_files").select("*"), context).eq("id", id).maybeSingle());
  },
};
